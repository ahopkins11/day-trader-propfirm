"""
=============================================================================
  STRATEGY: Opening Range Breakout (ORB)          strategies/orb.py
=============================================================================

  This file is the whole trading rule. Every tool (scanner, entry timer, exit
  planner, Time Machine) asks this file "is there a trade, and where are the
  entry, stop and target?" and nothing else in the repo decides that.

  To trade your own strategy instead, do not edit this file: copy
  strategies/template.py to strategies/<your_name>.py, fill in evaluate(), and
  set "strategy": "<your_name>" in trader/config.json. See strategies/README.md.

  The rule (same as upstream day-trader-skill, applied to futures):
    1. The opening range is the high and low of the first `range_minutes`
       of the regular session (9:30 to 9:45 ET for ES/NQ by default).
    2. Long:  the first bar that CLOSES above the range high is the entry.
       Short: the first bar that CLOSES below the range low (if allowed).
    3. Stop:  the range midpoint ("mid") or the far side of the range ("range").
    4. Target: `target_r` times the risk (1.0 = 1R).
    5. One signal per day: the first breakout wins.
=============================================================================
"""

NAME = "orb"
DESCRIPTION = "Opening range breakout: first close outside the opening range, stop at the midpoint, 1R target"

# Defaults. Override any of these in trader/config.json under "strategy_params".
PARAMS = {
    "range_minutes": 15,     # length of the opening range, a multiple of the bar size
    "direction": "long",     # "long", "short" or "both"
    "stop": "mid",           # "mid" = range midpoint, "range" = other side of the range
    "target_r": 1.0,         # target = entry + target_r x risk
    "min_volume_x": None,    # e.g. 1.5 = breakout bar needs 1.5x the range's average volume
}


def evaluate(bars, p, ctx):
    """
    bars  today's CLOSED regular-session bars, oldest first. Each bar is
          {"t": start, "end": close time, "i": slot from the open,
           "o", "h", "l", "c", "v"}; times are naive New York time.
    p     PARAMS merged with the config's strategy_params.
    ctx   {"open", "close", "now": datetimes, "bar_minutes": int,
           "spec": the contract (tick, point_value ...),
           "can_enter": function(bar) -> True if that bar's close is inside
                        your entry window (no_entries_before/after)}

    Return a dict:
      status   "forming" (not ready yet), "waiting" (ready, no trade yet)
               or "triggered"
      reason   one plain sentence
      levels   anything worth showing (here: the range)
      signal   None, or {"side": "long"|"short", "entry", "stop", "target",
                         "bar": the bar that triggered, "why": text}
    The tools round prices to the tick, check the stop is on the right side,
    and turn "waiting" into "expired" after your last entry time.
    """
    step = ctx["bar_minutes"]
    if p["range_minutes"] % step or p["range_minutes"] <= 0:
        raise ValueError("range_minutes must be a multiple of %d" % step)
    n = p["range_minutes"] // step
    rng = [b for b in bars if b["i"] < n]
    if len(rng) < n:
        return {"status": "forming", "signal": None, "levels": {},
                "reason": "%d of %d opening-range bars closed" % (len(rng), n)}

    hi = max(b["h"] for b in rng)
    lo = min(b["l"] for b in rng)
    mid = (hi + lo) / 2.0
    avg_v = sum(b["v"] for b in rng) / float(n)
    levels = {"range_high": hi, "range_low": lo, "range_mid": mid, "range_minutes": p["range_minutes"]}
    sides = {"long": ["long"], "short": ["short"], "both": ["long", "short"]}[p["direction"]]

    for b in bars:
        if b["i"] < n or not ctx["can_enter"](b):
            continue
        if p.get("min_volume_x") and avg_v and b["v"] < p["min_volume_x"] * avg_v:
            continue
        side = None
        if "long" in sides and b["c"] > hi:
            side = "long"
        elif "short" in sides and b["c"] < lo:
            side = "short"
        if not side:
            continue
        entry = b["c"]
        if side == "long":
            stop = mid if p["stop"] == "mid" else lo
            target = entry + p["target_r"] * (entry - stop)
        else:
            stop = mid if p["stop"] == "mid" else hi
            target = entry - p["target_r"] * (stop - entry)
        return {"status": "triggered", "levels": levels,
                "reason": "the %s bar closed %s the range" % (b["t"].strftime("%H:%M"),
                                                             "above" if side == "long" else "below"),
                "signal": {"side": side, "entry": entry, "stop": stop, "target": target, "bar": b,
                           "why": "close %s range %s" % (">" if side == "long" else "<",
                                                         "high %.2f" % hi if side == "long" else "low %.2f" % lo)}}

    last = bars[-1]["c"] if bars else None
    return {"status": "waiting", "signal": None, "levels": levels,
            "reason": "no close outside the range (%.2f to %.2f) yet; last close %.2f" % (lo, hi, last)}
